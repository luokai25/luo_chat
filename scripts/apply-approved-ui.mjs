import {readFile,appendFile,writeFile} from 'node:fs/promises';
const verify='<meta name="google-site-verification" content="y09hvb9dhGQPvM_sozzO_Q3z09BT30HekpDvlDsVR-w" />';
const [base,extra,index]=await Promise.all([readFile('public/luo-modern.css','utf8'),readFile('public/luo-approved.css','utf8'),readFile('public/index.html','utf8')]);
if(!index.includes(verify))throw Error('Google verification tag must be preserved exactly');
if(!extra.startsWith('/* Luo Chat approved WhatsApp-like mobile design')||extra.length<7000)throw Error('Approved mobile CSS unavailable');
if(!base.includes('/* Luo Chat approved WhatsApp-like mobile design'))await appendFile('public/luo-modern.css','\n'+extra);
const fixCSS='@media(max-width:999px){.app:not([data-screen=home]) #luoApprovedNav,.app.luo-calls-open #luoApprovedFab{display:none!important}}';
let modern=await readFile('public/luo-modern.css','utf8');
if(!modern.includes(fixCSS))await appendFile('public/luo-modern.css','\n'+fixCSS);
const script='<script defer src="/luo-approved.js"></script>';
if(!index.includes(script))await writeFile('public/index.html',index.replace('</body>',script+'</body>'));
let js=await readFile('public/luo-approved.js','utf8');
const oldMore="action('More options',()=>{$('luoModernMore')?.click()||clickTab('profile')})";
const newMore="action('More options',()=>{const more=$('luoModernMore');if(more)more.click();else clickTab('profile')})";
if(js.includes(oldMore))js=js.replace(oldMore,newMore);
else if(!js.includes(newMore))throw Error('Unexpected More handler, refusing to build');
const oldObs="if(app.dataset.screen!=='home')app.classList.remove('luo-calls-open');";
const newObs="if(app.dataset.screen!=='home'){closeCalls();if(active==='calls')active='chats';refresh()}";
if(js.includes(oldObs))js=js.replace(oldObs,newObs);
else if(!js.includes(newObs))throw Error('Unexpected Calls transition, refusing to build');
await writeFile('public/luo-approved.js',js);
console.log('Luo Chat approved UI: original features, Calls/More transitions, and Google verification preserved');
